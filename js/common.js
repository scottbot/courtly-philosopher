/* ---------------------------------------------------------------- squares */
FC.sq = (function () {
  const B = () => FC.board;
  const LABOUR = [4, 12, 17, 23, 30, 34, 41, 48, 57];
  // Which fixed verse translation (TRANSLATION_GUIDE.md id) belongs to which square.
  const VID = { 1: 's1', 4: 't0', 12: 't1', 17: 't2', 23: 't3', 30: 't4', 34: 't5', 41: 't6', 48: 't7', 57: 't8',
    7: 'h7', 10: 'h10', 15: 'h15', 20: 'h20', 26: 'h26', 28: 'h28', 32: 'h32', 36: 'h36', 39: 'h39',
    43: 'h43', 46: 'h46', 51: 'h51', 53: 'h53', 55: 'h55', 60: 'h60', 63: 'h63' };
  // The princeps (G) printed eight Labour couplets of its own, in this order (Lucero 2016,
  // collation tables). Its board is lost: we lay them on Cartaro's Labour squares in order.
  const G_LABOUR = { 12: 'g1', 17: 'g2', 23: 'g3', 30: 't5', 34: 't7', 41: 'g6', 48: 't4', 57: 't3' };

  function povertySquare(ed) { return ed === 'G' ? 59 : 60; }
  function annId(n, ed) {
    if (ed === 'G' && n === 59) return 'sq60';
    if (ed === 'G' && n === 60) return 'plain';
    return FC.annotations['sq' + n] ? 'sq' + n : 'plain';
  }
  function data(n) { return B().squares[n - 1]; }
  function adorned(n, ed) {
    if (ed === 'G' && n === 59) return true;
    return !!FC.annotations['sq' + n];
  }
  function name(n, ed) {
    const a = FC.annotations[annId(n, ed)];
    if (!a || a.id === 'plain') return `Square ${n}`;
    return a.title_en.replace(/\s*\(.*\)$/, '');
  }
  /** The verse on square n in edition ed: {en, lit, es_book, es_board, it_board, gloss_it} */
  function verse(n, ed) {
    const d = data(n), V = B().verses;
    let vid = VID[n];
    if (ed === 'G' && G_LABOUR[n]) vid = G_LABOUR[n];
    if (ed === 'G' && n === 59) vid = 'h60';
    if (ed === 'G' && n === 60) vid = null;
    const v = vid ? V[vid] : null;
    const onBoard = !(ed === 'G' && (G_LABOUR[n] || n === 59 || n === 60));
    return v ? {
      vid, en: v.en, lit: v.lit, es_book: v.es.replace(/\s*\((?:1587 )?princeps only\)/, ''),
      es_board: onBoard ? d.es : '', it_board: onBoard ? d.it : '', gloss_it: onBoard ? d.it_gloss : '',
      princeps_only: vid.startsWith('g'),
    } : null;
  }
  const tile = n => `img/sq/tile-${String(n).padStart(2, '0')}.jpg`;
  const detail = n => `img/sq/detail-${String(n).padStart(2, '0')}.jpg`;
  /** Barros's own prose about square n (Naples 1588 segments; Madrigal additions too). */
  function barros(n) {
    const tag = LABOUR.includes(n) ? ['labour', String(n)] : [String(n)];
    const C = FC.text.C.filter(s => s.kind !== 'rules' && s.squares.some(x => tag.includes(x)));
    const M = FC.text.M.filter(s => s.kind !== 'rules' && s.squares.includes(String(n)));
    return { C, M };
  }
  return { LABOUR, VID, G_LABOUR, data, name, verse, tile, detail, barros, adorned, annId, povertySquare };
})();

