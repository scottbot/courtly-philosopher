/* ---------------------------------------------------------------- viewer */
/**
 * FC.Viewer — shows the board sheet with pan & zoom (wheel, drag, pinch, buttons, keys),
 * an SVG overlay of the 63 squares (clickable, and reachable by keyboard when the viewer
 * has tools and an onSquare handler), and players' tokens.
 * Coordinates everywhere are fractions of the sheet (0..1).
 * The image climbs a ladder of sizes, fetching only the smallest one sharp enough for
 * the current zoom (each in the best format the browser decodes).
 */
const BOARD_LADDER = [['img/board/board-800.jpg', 800], ['img/board/board-1200.jpg', 1200],
  ['img/board/board-2000.jpg', 2000], ['img/board/board-full.jpg', 2594]];
FC.BOARD_ALT = 'Mario Cartaro’s engraved board, Naples 1588: a track of 63 numbered squares divided by balusters. ' +
  'A gate at bottom left leads to square 1; the numbers run counter-clockwise round the outer ring and then inward in a ' +
  'second ring to the palm at square 63, in the center. Emblematic figures fill the four corners. British Museum 1869,0410.2463.+';
FC.Viewer = class {
  constructor(container, opts = {}) {
    this.el = container;
    // wheel: zoom with the mouse wheel (false in the introduction, where the wheel scrolls the page)
    this.opts = Object.assign({ src: null, hotspots: true, tools: true, onSquare: null, tips: true, wheel: true }, opts);
    const S = FC.board.sheet;
    this.aspect = S.h / S.w;
    this.ladder = !this.opts.src || /board\/board-/.test(this.opts.src) ? BOARD_LADDER : null;
    this.level = -1;
    this.keyed = !!(this.opts.tools && this.opts.onSquare && this.opts.hotspots);
    this.el.classList.add('viewer');
    this.el.innerHTML = `
      <div class="stage">
        <img alt="${FC.util.esc(FC.BOARD_ALT)}"${this.ladder ? '' : ` src="${this.opts.src}"`}>
        <svg class="overlay" viewBox="0 0 1000 ${Math.round(1000 * this.aspect)}" preserveAspectRatio="none"${this.keyed ? '' : ' aria-hidden="true"'}><g class="hots"></g><g class="names" hidden aria-hidden="true"></g><g class="marks" aria-hidden="true"></g><g class="toks" aria-hidden="true"></g></svg>
      </div>
      ${this.opts.tools ? `<div class="viewer-tools"><button type="button" data-z="in" aria-label="Zoom in">+</button><button type="button" data-z="out" aria-label="Zoom out">−</button><button type="button" data-z="fit" aria-label="Show the whole board">⤢</button>
        <div class="pan-pad"><button type="button" data-pan="0,1" aria-label="Move the view up">↑</button><button type="button" data-pan="1,0" aria-label="Move the view left">←</button><button type="button" data-pan="-1,0" aria-label="Move the view right">→</button><button type="button" data-pan="0,-1" aria-label="Move the view down">↓</button></div></div>` : ''}
      <div class="label-tip" hidden></div>`;
    this.stage = this.el.querySelector('.stage');
    this.svg = this.el.querySelector('svg');
    this.tip = this.el.querySelector('.label-tip');
    this.s = 1; this.x = 0; this.y = 0;
    if (this.opts.hotspots) this.drawHotspots();
    this.bind();
    if (typeof ResizeObserver === 'function') { this.ro = new ResizeObserver(() => this.layout()); this.ro.observe(this.el); }
    else { this.ro = null; this._onResize = () => this.layout(); addEventListener('resize', this._onResize); }   // older browsers
    this.layout();
  }
  /** Stop observing the container (call before replacing a viewer with another). */
  destroy() { if (this.ro) this.ro.disconnect(); else removeEventListener('resize', this._onResize); }
  /** fraction → overlay units */
  u(p) { return [p[0] * 1000, p[1] * 1000 * this.aspect]; }
  drawHotspots() {
    const g = this.svg.querySelector('.hots');
    g.innerHTML = FC.board.squares.map(s => {
      const pts = s.quad.map(p => this.u(p).join(',')).join(' ');
      const kb = this.keyed ? ` role="button" tabindex="-1" aria-label="Square ${s.n}"` : '';
      return `<polygon class="hot" data-n="${s.n}" points="${pts}"${kb}><title>${s.n}</title></polygon>`;
    }).join('');
  }
  /** Move keyboard focus to square n on the board, bringing it into view. */
  focusHot(n) {
    n = FC.util.clamp(n, 1, 63);
    const p = this.svg.querySelector(`.hot[data-n="${n}"]`);
    if (!p) return;
    this.svg.querySelectorAll('.hot[tabindex="0"]').forEach(x => x.setAttribute('tabindex', '-1'));
    p.setAttribute('tabindex', '0');
    const ed = this.edition || 'C';
    p.setAttribute('aria-label', `Square ${n}${FC.sq.adorned(n, ed) ? ', ' + FC.sq.name(n, ed) : ''}`);
    this.lastHot = n;
    // keep the square on screen
    const c = FC.board.squares[n - 1].center, r = this.el.getBoundingClientRect();
    const px = this.x + c[0] * this.base * this.s, py = this.y + c[1] * this.base * this.aspect * this.s;
    if (px < 40 || py < 40 || px > r.width - 40 || py > r.height - 40) {
      this.x = r.width / 2 - c[0] * this.base * this.s; this.y = r.height / 2 - c[1] * this.base * this.aspect * this.s; this.apply(true);
    }
    p.focus({ preventScroll: true });
  }
  bind() {
    const el = this.el;
    let drag = null, pinch = null, moved = false;
    const pts = new Map();
    el.addEventListener('pointerdown', e => {
      el.setPointerCapture(e.pointerId);
      pts.set(e.pointerId, [e.clientX, e.clientY]);
      moved = false;
      if (pts.size === 1) drag = { x: e.clientX, y: e.clientY, ox: this.x, oy: this.y, t: e.target };
      if (pts.size === 2) { const [a, b] = [...pts.values()]; pinch = { d: Math.hypot(a[0] - b[0], a[1] - b[1]), s: this.s, cx: (a[0] + b[0]) / 2, cy: (a[1] + b[1]) / 2 }; drag = null; }
    });
    el.addEventListener('pointermove', e => {
      if (!pts.has(e.pointerId)) { this.hover(e); return; }
      pts.set(e.pointerId, [e.clientX, e.clientY]);
      if (pinch && pts.size === 2) {
        const [a, b] = [...pts.values()]; const d = Math.hypot(a[0] - b[0], a[1] - b[1]);
        this.zoomAt(pinch.s * d / pinch.d / this.s, pinch.cx, pinch.cy); moved = true; return;
      }
      if (drag) {
        const dx = e.clientX - drag.x, dy = e.clientY - drag.y;
        if (Math.abs(dx) + Math.abs(dy) > 4) moved = true;
        this.x = drag.ox + dx; this.y = drag.oy + dy; this.apply();
      }
    });
    const end = e => {
      pts.delete(e.pointerId);
      if (pts.size < 2) pinch = null;
      if (drag && !moved) this.click(drag.t, e);
      if (!pts.size) drag = null;
    };
    el.addEventListener('pointerup', end);
    el.addEventListener('pointercancel', e => { pts.delete(e.pointerId); drag = null; pinch = null; });
    el.addEventListener('pointerleave', () => { this.tip.hidden = true; });
    el.addEventListener('wheel', e => {
      if (!this.opts.wheel && !e.ctrlKey) return;                  // let the page scroll
      e.preventDefault(); this.zoomAt(Math.exp(-e.deltaY * 0.0016), e.clientX, e.clientY);
    }, { passive: false });
    el.querySelectorAll('[data-z], [data-pan]').forEach(b => b.addEventListener('pointerdown', e => e.stopPropagation()));
    el.querySelectorAll('[data-z]').forEach(b => b.addEventListener('click', e => {
      e.stopPropagation();
      const r = el.getBoundingClientRect();
      if (b.dataset.z === 'fit') this.fit(true);
      else this.zoomAt(b.dataset.z === 'in' ? 1.5 : 1 / 1.5, r.left + r.width / 2, r.top + r.height / 2, true);
    }));
    el.querySelectorAll('[data-pan]').forEach(b => b.addEventListener('click', e => {
      e.stopPropagation(); this.pan(...b.dataset.pan.split(',').map(Number));
    }));
    el.addEventListener('keydown', e => {
      const r = el.getBoundingClientRect();
      const hot = e.target.closest && e.target.closest('.hot');
      if (hot && this.keyed) {                                     // moving from square to square
        const n = +hot.dataset.n;
        const step = { ArrowRight: 1, ArrowUp: 1, ArrowLeft: -1, ArrowDown: -1, Home: -99, End: 99 }[e.key];
        if (step) { e.preventDefault(); this.focusHot(n + step); return; }
        if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); this.opts.onSquare(n); return; }
        if (e.key === 'Escape') { e.preventDefault(); e.stopPropagation(); el.focus(); return; }
      }
      if (e.target !== el) return;                                 // the buttons handle themselves
      if (e.key === '+' || e.key === '=') this.zoomAt(1.3, r.left + r.width / 2, r.top + r.height / 2, true);
      else if (e.key === '-' || e.key === '−') this.zoomAt(1 / 1.3, r.left + r.width / 2, r.top + r.height / 2, true);
      else if (e.key === '0') this.fit(true);
      else if (e.key === 'Enter' && this.keyed) this.focusHot(this.lastHot || 1);
      else {
        const P = { ArrowLeft: [1, 0], ArrowRight: [-1, 0], ArrowUp: [0, 1], ArrowDown: [0, -1] }[e.key];
        if (!P) return;
        this.pan(...P);
      }
      e.preventDefault();
    });
    if (this.opts.tools) {
      el.tabIndex = 0;
      el.setAttribute('role', 'group');
      el.setAttribute('aria-roledescription', 'board viewer');
      el.setAttribute('aria-label', 'The board. Arrow keys move the view, + and − zoom, 0 shows the whole board' +
        (this.keyed ? '; Enter goes to the squares, where the arrow keys step from square to square and Enter opens one.' : '.'));
    }
  }
  /** Move the view by a fifth of its width (dx) or height (dy). */
  pan(dx, dy) { this.x += dx * this.W * 0.2; this.y += dy * this.H * 0.2; this.apply(true); }
  hover(e) {
    if (!this.opts.tips) return;
    const t = e.target.closest && e.target.closest('.hot');
    if (!t) { this.tip.hidden = true; return; }
    const n = +t.dataset.n, ed = this.edition || 'C';
    const r = this.el.getBoundingClientRect();
    this.tip.textContent = `${n} · ${FC.sq.name(n, ed)}`;
    this.tip.hidden = false;
    this.tip.style.left = Math.min(e.clientX - r.left + 14, r.width - 180) + 'px';
    this.tip.style.top = (e.clientY - r.top + 14) + 'px';
  }
  click(target) {
    const t = target.closest && target.closest('.hot');
    if (t && this.opts.onSquare) this.opts.onSquare(+t.dataset.n);
  }
  layout() {
    const r = this.el.getBoundingClientRect();
    this.W = r.width; this.H = r.height;
    const baseW = Math.min(r.width, r.height / this.aspect);
    this.base = baseW;
    this.stage.style.width = baseW + 'px';
    this.stage.style.height = baseW * this.aspect + 'px';
    if (!this._fitted) { this.fit(false); this._fitted = true; } else this.apply();
  }
  fit(anim) {
    this.s = 1;
    this.x = (this.W - this.base) / 2; this.y = (this.H - this.base * this.aspect) / 2;
    this.apply(anim);
  }
  zoomAt(f, cx, cy, anim) {
    const r = this.el.getBoundingClientRect();
    const ns = FC.util.clamp(this.s * f, 0.6, 9);
    f = ns / this.s;
    const px = cx - r.left, py = cy - r.top;
    this.x = px - (px - this.x) * f; this.y = py - (py - this.y) * f; this.s = ns;
    this.apply(anim);
  }
  /** Zoom so that the rectangle (fractions of the sheet) fills the view. */
  focusRect(x0, y0, x1, y1, anim = true, pad = 0.08) {
    const w = (x1 - x0) * this.base, h = (y1 - y0) * this.base * this.aspect;
    const s = FC.util.clamp(Math.min(this.W / (w * (1 + pad * 2)), this.H / (h * (1 + pad * 2))), 0.6, 9);
    this.s = s;
    this.x = this.W / 2 - ((x0 + x1) / 2) * this.base * s;
    this.y = this.H / 2 - ((y0 + y1) / 2) * this.base * this.aspect * s;
    this.apply(anim);
  }
  focusSquare(n, anim = true, zoom = 3.2) {
    const q = FC.board.squares[n - 1].quad;
    const xs = q.map(p => p[0]), ys = q.map(p => p[1]);
    const cx = (Math.min(...xs) + Math.max(...xs)) / 2, cy = (Math.min(...ys) + Math.max(...ys)) / 2;
    const half = 0.5 / zoom;
    this.focusRect(cx - half, cy - half * 0.8, cx + half, cy + half * 0.8, anim, 0);
  }
  /** Fetch the smallest board image sharp enough for the current zoom, if not already shown. */
  sharpen() {
    if (!this.ladder || !this.base) return;
    const need = this.base * this.s * Math.min(window.devicePixelRatio || 1, 2);
    let k = this.ladder.findIndex(([, w]) => w >= need * 0.9);
    if (k < 0) k = this.ladder.length - 1;
    if (k <= this.level) return;
    this.level = k;
    FC.img.best.then(ext => {
      if (this.level !== k) return;                       // a larger one was asked for meanwhile
      const url = FC.img.swap(this.ladder[k][0], ext), img = this.stage.querySelector('img');
      if (!img.getAttribute('src')) { img.src = url; return; }
      const hi = new Image();
      hi.onload = () => { if (this.level === k) img.src = url; };
      hi.src = url;
    });
  }
  apply(anim) {
    // keep the sheet in view: center it when smaller than the viewer, otherwise stop at its edges
    const w = this.base * this.s, h = this.base * this.aspect * this.s;
    this.x = w <= this.W ? (this.W - w) / 2 : FC.util.clamp(this.x, this.W - w, 0);
    this.y = h <= this.H ? (this.H - h) / 2 : FC.util.clamp(this.y, this.H - h, 0);
    this.sharpen();
    this.stage.style.transition = anim ? 'transform .7s cubic-bezier(.3,.1,.2,1)' : 'none';
    this.stage.style.transform = `translate(${this.x}px, ${this.y}px) scale(${this.s})`;
  }
  /** Mark squares with a CSS class ('focus' or 'variant'). */
  mark(ns, cls) {
    this.svg.querySelectorAll('.hot.' + cls).forEach(p => p.classList.remove(cls));
    [].concat(ns || []).forEach(n => { const p = this.svg.querySelector(`.hot[data-n="${n}"]`); if (p) p.classList.add(cls); });
  }
  /** Show where edition ed's board differs from Cartaro's (the princeps' Poverty on 59). */
  showEdition(ed) {
    const r = FC.rules(ed);
    this.edition = ed;
    this.mark(r.poverty !== 60 ? [r.poverty] : [], 'variant');
    this.labels(r.boardMarks);
  }
  /** English names written over the adorned squares (a reading aid; off by default). */
  names(on, ed = 'C') {
    const g = this.svg.querySelector('.names');
    g.hidden = !on;
    if (!on) return;
    let h = '';
    for (let n = 1; n <= 63; n++) {
      if (!FC.sq.adorned(n, ed)) continue;
      const nm = FC.sq.name(n, ed).replace(/^The /, ''), c = this.u(FC.board.squares[n - 1].center);
      const w = nm.length * 6.4 + 10;
      h += `<g transform="translate(${c[0].toFixed(1)},${(c[1] + 18).toFixed(1)})"><rect x="${-w / 2}" y="-9" width="${w}" height="16" rx="3" class="name-bg"/><text class="name-tx" text-anchor="middle" y="3">${FC.util.esc(nm)}</text></g>`;
    }
    g.innerHTML = h;
  }
  /** Small labels written on the overlay (used for the princeps' Poverty on 59). */
  labels(list) {
    const g = this.svg.querySelector('.marks');
    g.innerHTML = (list || []).map(l => {
      const c = this.u(FC.board.squares[l.n - 1].center);
      return `<text class="variant-label" x="${c[0]}" y="${c[1] + 26}" text-anchor="middle">${FC.util.esc(l.text)}</text>`;
    }).join('');
  }
  /**
   * Draw tokens. players: [{id, token, color, pos}] ; pos 0 = before the gate.
   * Several tokens on the same place are fanned out.
   */
  tokens(players) {
    const g = this.svg.querySelector('.toks');
    const byPos = {};
    players.forEach(p => { (byPos[p.pos] = byPos[p.pos] || []).push(p); });
    const gate = this.u([0.13, 0.85]);
    let out = '';
    Object.entries(byPos).forEach(([pos, ps]) => {
      pos = +pos;
      const c = pos === 0 ? gate : this.u(FC.board.squares[pos - 1].center);
      ps.forEach((p, i) => {
        const k = ps.length, ang = (i / k) * Math.PI * 2, rad = k > 1 ? 20 : 0;
        const x = c[0] + Math.cos(ang) * rad, y = c[1] + Math.sin(ang) * rad;
        out += `<g class="token" data-player="${p.id}" transform="translate(${x.toFixed(1)},${y.toFixed(1)})">
          <circle r="21" fill="rgba(250,245,234,.92)" stroke="${p.color}" stroke-width="4"/>
          <g transform="scale(0.85)">${FC.tokens.glyph(p.token)}</g></g>`;
      });
    });
    g.innerHTML = out;
  }
};

