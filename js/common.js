/* A citation link opens its full reference just after itself, as a small disclosure:
   focus moves into it, Tab continues from it, Escape closes it and returns to the link. */
(function () {
  let pop = null;
  function bibFor(key) { return (FC.biblio || []).find(b => b.key === key); }
  function hide() {
    if (!pop) return;
    if (pop._for) pop._for.setAttribute('aria-expanded', 'false');
    pop.remove(); pop = null;
  }
  document.addEventListener('click', e => {
    const a = e.target.closest('a.cite');
    if (!a) { if (pop && !e.target.closest('.cite-pop')) hide(); return; }
    const b = bibFor(a.dataset.key);
    if (!b) return;                              // unknown: let the link work
    e.preventDefault();
    const was = pop && pop._for === a;
    hide();
    if (was) return;                             // a second click closes it
    // only a web address or a page of this site, and escaped: the href comes from the content
    const raw = a.getAttribute('href') || '';
    const href = /^(https?:\/\/|(?:text|about|atlas)\.html(?:#|$)|#)/.test(raw) ? raw : 'about.html#bib-' + b.key;
    const go = href.startsWith('text.html') ? 'Open this page of the book →' : href.startsWith('http') ? 'Open the source →' : 'See the bibliography →';
    pop = FC.util.html(`<span class="cite-pop" role="group" aria-label="Reference" tabindex="-1">${b.html}<a class="go" href="${FC.util.esc(href)}"${href.startsWith('http') ? ' target="_blank" rel="noopener"' : ''}>${go}</a></span>`);
    pop._for = a; a.setAttribute('aria-expanded', 'true');
    a.after(pop);                                // next in the tab order
    const r = a.getBoundingClientRect(), pr = pop.getBoundingClientRect();
    pop.style.left = FC.util.clamp(r.left, 16, innerWidth - pr.width - 16) + 'px';
    pop.style.top = (r.bottom + pr.height + 8 < innerHeight ? r.bottom + 6 : Math.max(8, r.top - pr.height - 6)) + 'px';
    pop.focus({ preventScroll: true });
    pop.addEventListener('keydown', ev => {
      if (ev.key === 'Escape') { ev.stopPropagation(); ev.preventDefault(); const o = pop && pop._for; hide(); if (o) o.focus(); }
    });
    pop.addEventListener('focusout', ev => {
      if (pop && ev.relatedTarget && !pop.contains(ev.relatedTarget) && ev.relatedTarget !== a) hide();
    });
  });
  // scrolling hides it (it is fixed in place), unless the scroll came from moving focus inside it
  addEventListener('scroll', () => { if (pop && !pop.contains(document.activeElement)) hide(); }, { passive: true, capture: true });
})();

