/**
 * FC.annotate(n, edition) → HTML for square n (1..63), or for a feature id
 * ('gate', 'centre-sea', 'corner-clock', 'title', …).
 */
FC.annotate = function (key, ed = 'C', opts = {}) {
  const { esc } = FC.util;
  const isSq = typeof key === 'number';
  const aid = isSq ? FC.sq.annId(key, ed) : key;
  const a = FC.annotations[aid] || FC.annotations.plain;
  const n = isSq ? key : null;
  const title = isSq ? FC.sq.name(n, ed) : a.title_en;
  const d = isSq ? FC.sq.data(n) : null;
  const r = FC.rules(ed);
  let h = '';
  h += `<div class="sq-head">${n ? `<div class="sq-num">${n}</div>` : ''}<div><h2 class="sq-title">${esc(title)}</h2>`;
  const subs = [];
  if (a.title_es && a.id !== 'plain') subs.push(`<span lang="es">${esc(a.title_es)}</span>`);
  if (a.board_it && !/^\(none/.test(a.board_it) && a.id !== 'plain') subs.push(`<span lang="it">${esc(a.board_it)}</span>`);
  h += `<div class="sq-sub">${subs.join(' · ')}</div></div></div>`;

  // image
  const img = n ? FC.sq.detail(n) : FC.featureImage(aid);
  if (img) h += `<figure class="sq-figure">${FC.img.pic(img, `${title}: detail of the board`, 'loading="lazy"')}<figcaption>Detail of Cartaro’s board (Naples 1588). © The Trustees of the British Museum.${n ? ` <a href="#" data-show-on-board="${n}">Show on the whole board</a>` : ''}</figcaption></figure>`;

  // edition note for the princeps' Poverty
  if (n && n === r.poverty && r.poverty !== 60) h += `<p class="notice">In the first edition (Madrid, widow of Alonso Gómez, 1587) Poverty stands on square <b>${r.poverty}</b>, not 60; the board printed with that edition is lost. We show Cartaro’s picture of square 60 here.</p>`;
  if (n && r.plain.includes(n)) h += `<p class="notice">In the first edition Poverty stands on ${r.poverty}, so under that edition’s rules this square is plain. On the surviving board (and in the later editions) it is Poverty.</p>`;

  // verse
  const v = n ? FC.sq.verse(n, ed) : null;
  if (v) {
    const lines = t => esc(t).replace(' / ', '<br>');
    h += `<div class="verse"><div class="en">${lines(v.en)}</div><div class="lit">Literally: ${esc(v.lit)}</div><div class="orig">`;
    if (v.es_board) h += `<div><b>Spanish, on the board</b><span lang="es">${lines(v.es_board)}</span></div>`;
    if (v.it_board) h += `<div><b>Italian, on the board</b><span lang="it">${lines(v.it_board)}</span>${v.gloss_it ? `<div class="small muted">(${esc(v.gloss_it)})</div>` : ''}</div>`;
    if (!v.es_board && ed === 'G' && FC.sq.G_LABOUR[n]) h += `<div class="small muted">Cartaro’s board, made for the later text, has a different couplet here: <i lang="es">${esc(FC.sq.data(n).es)}</i>.</div>`;
    // whose Spanish this is (CIT-03): Lucero's quotation of G, or the Naples book
    const bookLab = v.book === 'G'
      ? `Madrid 1587, first edition, as quoted by Lucero Sánchez <span class="cites">(<a class="cite" href="about.html#bib-sanchezEdicionesAntiguasFilosofia2016oct16" data-key="sanchezEdicionesAntiguasFilosofia2016oct16" aria-expanded="false">Lucero Sánchez 2016, 187–88</a>)</span>`
      : v.book === 'C-not-G' ? 'Naples 1588 book (the first edition’s wording is not known to us)' : 'Naples 1588 book';
    h += `<div><b>Spanish, ${bookLab}${v.princeps_only ? '; this couplet only in the first edition' : ''}</b><span lang="es">${lines(v.es_book)}</span></div>`;
    if (v.es_m) h += `<div><b>Spanish, Madrid 1587 (Madrigal), in Ciompi and Seville’s modernized transcription</b><span lang="es">${lines(v.es_m)}</span></div>`;
    h += `</div></div>`;
  }
  // rule
  if (a.rule_short || (d && d.rule)) {
    h += `<div class="rulebox"><div class="ic" aria-hidden="true">☞</div><div>${a.rule_short || ''}`;
    if (d && d.rule) h += `<div class="lab">On the board: <i lang="it">${esc(d.rule)}</i>${d.rule_en ? ` — ${esc(d.rule_en)}` : ''}</div>`;
    h += `</div></div>`;
  }
  const sect = (t, body, open) => body ? `<details class="sect"${open ? ' open' : ''}><summary>${t}</summary>${body}</details>` : '';
  h += sect('What you see', a.see, true);
  h += sect('Why it is here', a.why, true);
  if (n) {
    const b = FC.sq.barros(n);
    if (b.C.length) {
      let bh = `<p class="small muted">Barros’s own explanation, from the Naples 1588 book (Spanish as printed; English translation by this edition). <a href="text.html#${esc(b.C[0].id)}">Read it in the whole book →</a></p>`;
      b.C.forEach(s => {
        bh += `<div class="barros-seg"><div class="meta">${s.page ? 'p. ' + esc(s.page) : 'leaf ' + esc(s.sig)} · Naples 1588</div><div class="es" lang="es">${esc(s.es).replace(/ \/ /g, '<br>')}</div><div class="en">${s.kind === 'verse' ? esc(s.en).replace(' / ', '<br>') : s.en}</div></div>`;
      });
      if (b.M.length && ed === 'M') {   // Madrigal's additions are not in G or C
        bh += `<p class="small muted">Additions and differences in the Madrid (Madrigal) edition of 1587, from Ciompi and Seville’s modernized transcription:</p>`;
        b.M.forEach(s => { bh += `<div class="barros-seg"><div class="meta">fol. ${esc(s.fol)} · Madrid 1587 (Madrigal)</div><div class="es" lang="es">${esc(s.es)}</div><div class="en">${s.en}</div></div>`; });
      }
      h += sect('What Barros says', bh, false);
    }
  }
  h += sect('Historical context', a.context, false);
  h += sect('Differences between the editions', a.variants, false);
  h += sect('What scholars say', a.readings, false);
  if (n && FC.sq.LABOUR.includes(n) && FC.annotations.labour) {
    const L = FC.annotations.labour;
    h += sect('About all nine Labor squares', L.why + L.context + L.variants + L.readings, false);
  }
  if (n && d && d.desc && aid === 'plain') h += `<p class="small muted">On the board: ${esc(d.desc)}</p>`;
  return h;
};
