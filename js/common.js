/* ---------------------------------------------------------------- squares */
FC.sq = (function () {
  const B = () => FC.board;
  const LABOUR = [4, 12, 17, 23, 30, 34, 41, 48, 57];
  // Which fixed verse translation (TRANSLATION_GUIDE.md id) belongs to which square.
  const VID = { 1: 's1', 4: 't0', 12: 't1', 17: 't2', 23: 't3', 30: 't4', 34: 't5', 41: 't6', 48: 't7', 57: 't8',
    7: 'h7', 10: 'h10', 15: 'h15', 20: 'h20', 26: 'h26', 28: 'h28', 32: 'h32', 36: 'h36', 39: 'h39',
    43: 'h43', 46: 'h46', 51: 'h51', 53: 'h53', 55: 'h55', 60: 'h60', 63: 'h63' };
  const G_LABOUR = FC.EDITION_RULES.G.labour;

  function annId(n, ed) {
    const r = FC.rules(ed);
    if (n === r.poverty && r.poverty !== 60) return 'sq60';
    if (r.plain.includes(n)) return 'plain';
    return FC.annotations['sq' + n] ? 'sq' + n : 'plain';
  }
  function data(n) { return B().squares[n - 1]; }
  function adorned(n, ed) {
    if (n === FC.rules(ed).poverty) return true;
    if (FC.rules(ed).plain.includes(n)) return false;
    return !!FC.annotations['sq' + n];
  }
  function name(n, ed) {
    const a = FC.annotations[annId(n, ed)];
    if (!a || a.id === 'plain') return `Square ${n}`;
    return a.title_en.replace(/\s*\(.*\)$/, '');
  }
  /** The verse on square n in edition ed:
      {vid, en, lit, es_book, book (whose Spanish es_book is: 'C', 'G' or 'C-not-G'),
       es_board, it_board, gloss_it, princeps_only, es_m (Madrigal's own wording, if recorded)} */
  function verse(n, ed) {
    const d = data(n), V = B().verses, r = FC.rules(ed);
    let vid = VID[n];
    if (r.labour && r.labour[n]) vid = r.labour[n];
    if (n === r.poverty) vid = 'h60';
    if (r.plain.includes(n)) vid = null;
    const v = vid ? V[vid] : null;
    if (!v) return null;
    const moved = ed === 'G' && (G_LABOUR[n] || n === r.poverty || r.plain.includes(n));
    const gEs = ed === 'G' && G_LABOUR[n] && B().G_labour_es && B().G_labour_es[n];
    const mSeg = ed === 'M' && FC.text ? FC.text.M.find(s => s.kind === 'verse' && s.squares.includes(String(n))) : null;
    return {
      vid, en: v.en, lit: v.lit,
      es_book: gEs || v.es.replace(/\s*\((?:1587 )?princeps only\)/, ''),
      book: gEs ? 'G' : ed === 'G' ? 'C-not-G' : 'C',
      es_m: mSeg ? mSeg.es : '',
      es_board: moved ? '' : d.es, it_board: moved ? '' : d.it, gloss_it: moved ? '' : d.it_gloss,
      princeps_only: vid.startsWith('g'),
    };
  }
  const pad = n => String(n).padStart(2, '0');
  const tile = n => `img/sq/tile-${pad(n)}.jpg`;
  const detail = n => `img/sq/detail-${pad(n)}.jpg`;
  /** Barros's own prose about square n (Naples 1588 segments; Madrigal additions too). */
  function barros(n) {
    const tag = LABOUR.includes(n) ? ['labour', String(n)] : [String(n)];
    const C = FC.text.C.filter(s => s.kind !== 'rules' && s.squares.some(x => tag.includes(x)));
    const M = FC.text.M.filter(s => s.kind !== 'rules' && s.squares.includes(String(n)));
    return { C, M };
  }
  return { LABOUR, VID, G_LABOUR, data, name, verse, tile, detail, barros, adorned, annId };
})();

