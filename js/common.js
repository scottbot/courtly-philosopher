  const best = probe(AVIF).then(a => a ? 'avif' : probe(WEBP).then(w => w ? 'webp' : 'jpg'));
  const swap = (src, ext) => ext === 'jpg' ? src : src.replace(/\.jpg$/, '.' + ext);
  /** <picture> for a .jpg that has twins. attrs: extra attributes for the <img>;
      srcset: [[url, width], …] for a size ladder, with sizes. */
