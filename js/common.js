/* =========================================================================
   common.js — shared by every page.

   Contents
     FC.util        tiny DOM helpers
     FC.prefs       remembered choices (edition, theme, citations) — optional,
                    wrapped in try/catch because storage may be unavailable
     FC.sq          what we know about each square (names, kinds, verses, images)
     FC.tokens      the players' markers, drawn as small SVGs
     FC.Viewer      the pan-and-zoom board with clickable squares and tokens
     FC.annotate    builds the full annotation of a square (used by Play and Atlas)
     FC.drawer      a side sheet for reading annotations without leaving the page
     citation pop-ups, theme button, "hide references" toggle

   Data (window.FC.board, .annotations, .text, .biblio, .story) comes from
   data/*.js, generated by tools/build_data.py from the files in content/.
   ========================================================================= */
window.FC = window.FC || {};

/* ---------------------------------------------------------------- util */
FC.util = {
  $: (sel, root = document) => root.querySelector(sel),
  $$: (sel, root = document) => Array.from(root.querySelectorAll(sel)),
  esc: s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c])),
  /** Create an element from an HTML string. */
  html(str) { const t = document.createElement('template'); t.innerHTML = str.trim(); return t.content.firstElementChild; },
  clamp: (v, a, b) => Math.max(a, Math.min(b, v)),
  plural: (n, one, many) => `${n} ${Math.abs(n) === 1 ? one : many}`,
};

/* ---------------------------------------------------------------- prefs */
FC.prefs = {
  // keys are prefixed because every GitHub Pages site of one user shares one storage origin
  get(k, d) { try { const v = localStorage.getItem('filosofia-cortesana:' + k); return v === null ? d : JSON.parse(v); } catch (e) { return d; } },
  set(k, v) { try { localStorage.setItem('filosofia-cortesana:' + k, JSON.stringify(v)); } catch (e) { /* storage unavailable: fine */ } },
};

