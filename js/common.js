(function () {
  const root = document.documentElement;
  const t = FC.prefs.get('theme', null);
  if (t === 'dark' || t === 'light') root.dataset.theme = t;
  const isDark = () => root.dataset.theme ? root.dataset.theme === 'dark' : matchMedia('(prefers-color-scheme: dark)').matches;
  document.addEventListener('DOMContentLoaded', () => {
    const btn = document.querySelector('.theme-btn');
    if (btn) {
      btn.setAttribute('aria-label', 'Dark theme');
      btn.setAttribute('aria-pressed', String(isDark()));
      btn.addEventListener('click', () => {
        root.dataset.theme = isDark() ? 'light' : 'dark';
        FC.prefs.set('theme', root.dataset.theme);
        btn.setAttribute('aria-pressed', String(isDark()));
      });
    }
    if (FC.prefs.get('hideCites', false)) document.body.classList.add('hide-cites');
    FC.syncCiteToggles();
  });
  document.addEventListener('click', e => {
    if (!e.target.closest('[data-toggle-cites]')) return;
    const on = document.body.classList.toggle('hide-cites');
    FC.prefs.set('hideCites', on);
    FC.syncCiteToggles();
  });
})();

