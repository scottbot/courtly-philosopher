/* ---------------------------------------------------------------- drawer */
FC.drawer = (function () {
  let back, dr, body, titleEl, onClose = null, openedAt = 0, opener = null;
  const behind = () => Array.from(document.body.children).filter(el => el !== dr && el !== back);
  function ensure() {
    if (dr) return;
    back = FC.util.html('<div class="drawer-backdrop"></div>');
    dr = FC.util.html(`<aside class="drawer" role="dialog" aria-modal="true" aria-label="Annotation">
      <div class="drawer-head"><span class="grow sc drawer-title"></span><button class="btn small" data-close>Close ✕</button></div>
      <div class="drawer-body"></div></aside>`);
    document.body.append(back, dr);
    body = dr.querySelector('.drawer-body'); titleEl = dr.querySelector('.drawer-title');
    dr.inert = true;
    // a touch that opened the drawer also sends a click to the backdrop beneath it: ignore that one
    back.addEventListener('click', () => { if (performance.now() - openedAt > 400) close(); });
    dr.querySelector('[data-close]').addEventListener('click', close);
    document.addEventListener('keydown', e => { if (e.key === 'Escape' && dr.classList.contains('open')) close(); });
  }
  function open(html, title = '', cb = null) {
    ensure(); body.innerHTML = html; titleEl.textContent = title; body.scrollTop = 0; onClose = cb;
    opener = document.activeElement; openedAt = performance.now();
    dr.setAttribute('aria-label', title || 'Annotation');
    dr.inert = false; behind().forEach(el => { el.inert = true; });
    back.classList.add('open'); dr.classList.add('open');
    dr.tabIndex = -1; dr.focus({ preventScroll: true });
  }
  function close() {
    if (!dr || !dr.classList.contains('open')) return;
    back.classList.remove('open'); dr.classList.remove('open');
    dr.inert = true; behind().forEach(el => { el.inert = false; });
    if (opener && opener.isConnected) opener.focus({ preventScroll: true });
    if (onClose) { const f = onClose; onClose = null; f(); }
  }
  return { open, close, get body() { ensure(); return body; } };
})();

/* ---------------------------------------------------------------- citations */
(function () {
  let pop = null;
  function bibFor(key) { return (FC.biblio || []).find(b => b.key === key); }
  function hide() { if (pop) { pop.remove(); pop = null; } }
  document.addEventListener('click', e => {
    const a = e.target.closest('a.cite');
    if (!a) { if (pop && !e.target.closest('.cite-pop')) hide(); return; }
    const b = bibFor(a.dataset.key);
    if (!b) return;                              // unknown: let the link work
    e.preventDefault(); hide();
    const href = a.getAttribute('href');
    pop = FC.util.html(`<div class="cite-pop" role="note">${b.html}<a class="go" href="${href}"${href.startsWith('http') ? ' target="_blank" rel="noopener"' : ''}>${href.startsWith('text.html') ? 'Open this page of the book →' : href.startsWith('http') ? 'Open the source →' : 'See the bibliography →'}</a></div>`);
    document.body.append(pop);
    const r = a.getBoundingClientRect(), pr = pop.getBoundingClientRect();
    pop.style.left = FC.util.clamp(r.left, 16, innerWidth - pr.width - 16) + 'px';
    pop.style.top = (r.bottom + pr.height + 8 < innerHeight ? r.bottom + 6 : Math.max(8, r.top - pr.height - 6)) + 'px';
  });
  addEventListener('scroll', hide, { passive: true, capture: true });
})();

