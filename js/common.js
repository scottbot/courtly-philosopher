(function () {
  const root = document.documentElement;
  const t = FC.prefs.get('theme', null);
  if (t) root.dataset.theme = t;
  document.addEventListener('DOMContentLoaded', () => {
    const btn = document.querySelector('.theme-btn');
    if (btn) btn.addEventListener('click', () => {
      const dark = root.dataset.theme ? root.dataset.theme === 'dark' : matchMedia('(prefers-color-scheme: dark)').matches;
      root.dataset.theme = dark ? 'light' : 'dark';
      FC.prefs.set('theme', root.dataset.theme);
    });
    if (FC.prefs.get('hideCites', false)) document.body.classList.add('hide-cites');
    const cb = document.querySelector('[data-toggle-cites]');
    if (cb) {
      cb.textContent = document.body.classList.contains('hide-cites') ? 'Show references in the text' : 'Hide references in the text';
      cb.addEventListener('click', () => {
        const on = document.body.classList.toggle('hide-cites');
        FC.prefs.set('hideCites', on);
        cb.textContent = on ? 'Show references in the text' : 'Hide references in the text';
      });
    }
  });
})();

